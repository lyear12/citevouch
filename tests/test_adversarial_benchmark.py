"""CV-016: an adversarial evidence benchmark whose expectations were measured.

The tool answers one question - *is this quote on that page* - and three other
questions get confused with it: did the reader (the PDF extractor) produce the
words at all, does the passage support the sentence, and is the source the file
the author meant. This module keeps them apart by pinning a data file in which
every case carries a human ``support`` label, a measured ``expected`` alignment
result, and a provenance record.

Two rules the tests enforce, because both were violated by prose before:

* a recorded expectation is a **measurement**, not a hope. Each case is re-run
  against the matcher and must produce the recorded tier, ``found`` flag, page,
  spanned pages and similarity. When behaviour changes the file must change with
  it, in the same commit;
* a disagreement between the design intent and the measurement is only allowed
  if the file names it in ``known_gaps`` with a reason. Closing a gap therefore
  fails this test until the entry is removed, and opening one fails it until the
  entry is written. Neither can happen quietly.

``tests/fixtures/adversarial-cases.json`` was generated on 2026-11-15 against
citevouch 0.28.0 with pypdf 6.16.1 (see ``measured_with`` inside it) and is
regenerated by re-running the same measurements; the numbers in it are not
hand-written.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from citevouch import matching, sources

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "tests" / "fixtures" / "adversarial-cases.json"
DOC = ROOT / "docs" / "adversarial-benchmark.md"
DEMO = ROOT / "demo"
DEMO_PAPERS = sorted((DEMO / "papers").glob("*.pdf"))
README = ROOT / "README.md"

DATA = json.loads(FIXTURE.read_text(encoding="utf-8"))
CASES = DATA["cases"]
HELD_OUT = DATA["held_out"]
GAPS = {gap["id"]: gap["measured"] for gap in DATA["known_gaps"]}


def _pages(case: dict) -> list[sources.PageText]:
    """The pages a case is measured against, built the way the CLI builds them."""
    if case["pages"] is not None:
        return [
            sources.PageText(number=index, text=text)
            for index, text in enumerate(case["pages"], start=1)
        ]
    path = ROOT / case["source"]
    assert path.is_file(), f"{case['id']}: the source it names is not in this checkout"
    pages, problem = sources.extract_pages(path, DEMO, use_cache=False)
    assert problem is None, f"{case['id']}: {problem}"
    return pages


def _measure(case: dict) -> dict:
    match = matching.find_in_pages(case["quote"], _pages(case))
    return {
        "tier": match.tier,
        "found": match.found,
        "page": match.page,
        "spanned": list(match.spanned),
        "similarity": round(match.similarity, 4),
    }


def _disagrees(case: dict) -> bool:
    """Whether the design intent is contradicted by what the matcher does."""
    if case["intent"] == "undecidable":
        return False
    return case["expected"]["found"] != (case["intent"] == "should_find")


def _all_cases() -> list[dict]:
    return CASES + HELD_OUT


def test_the_records_are_measurements_not_hopes() -> None:
    """Every case must still do what the file says it does."""
    drifted = []
    for case in _all_cases():
        now = _measure(case)
        if now != case["expected"]:
            drifted.append(f"{case['id']}: recorded {case['expected']} but measured {now}")
    assert not drifted, (
        "the matcher changed under a recorded expectation; update the fixture in the same "
        "commit, deliberately:\n" + "\n".join(drifted)
    )


def test_intent_and_measurement_agree_unless_the_gap_is_declared() -> None:
    """A case whose design intent the matcher contradicts must be named."""
    undeclared = [
        case["id"] for case in _all_cases() if _disagrees(case) and case["id"] not in GAPS
    ]
    assert not undeclared, (
        "these cases say one thing and do another without a known_gaps entry: "
        + ", ".join(undeclared)
    )


def test_the_declared_gaps_still_exist_and_are_still_gaps() -> None:
    """A gap that closes must be removed from the file, not left standing."""
    by_id = {case["id"]: case for case in _all_cases()}
    stale = []
    for gap_id, reason in GAPS.items():
        case = by_id.get(gap_id)
        if case is None:
            stale.append(f"{gap_id}: declared as a gap but no longer a case")
        elif not _disagrees(case):
            stale.append(
                f"{gap_id}: declared as a gap but the matcher now satisfies its intent"
            )
        elif not reason.strip():
            stale.append(f"{gap_id}: declared without a reason")
    assert not stale, (
        "the gap list no longer matches reality; when a gap closes, delete its entry and say so "
        "in the changelog:\n" + "\n".join(stale)
    )


def test_the_three_axes_are_named_separately() -> None:
    """Alignment, extraction and support are three questions, and the file says so."""
    axes = DATA["axes"]
    assert set(axes) == {"alignment", "extraction", "support"}
    assert "matcher" in axes["alignment"]
    assert "reader" in axes["extraction"] or "file" in axes["extraction"]
    assert "human" in axes["support"]
    assert "never computed" in axes["support"]


def test_a_support_label_is_never_a_matcher_verdict() -> None:
    """The whole point: ``paraphrase-faithful`` is supported by a reader and absent to us."""
    labelled = {case["id"]: case for case in _all_cases()}
    faithful = labelled["paraphrase-faithful"]
    assert faithful["human_support"]["label"] == "supported"
    assert faithful["intent"] == "should_not_find"
    assert faithful["expected"]["found"] is False
    # And the mirror image: words on the page whose support nobody has judged.
    cjk = labelled["cjk-exact"]
    assert cjk["human_support"]["label"] == "unknown"
    assert cjk["expected"]["found"] is True


def test_the_support_labels_cover_every_value_the_axis_can_take() -> None:
    labels = {case["human_support"]["label"] for case in _all_cases()}
    assert {"supported", "not_supported", "unknown"} <= labels


def test_every_case_carries_provenance_and_a_licence_where_it_needs_one() -> None:
    for case in _all_cases():
        provenance = case["provenance"]
        assert provenance["kind"] in {"authored", "real-pdf"}, case["id"]
        if provenance["kind"] == "real-pdf":
            assert "licence" in provenance, case["id"]
            assert (ROOT / provenance["path"]).is_file(), case["id"]
            assert case["source"] == provenance["path"], case["id"]
        else:
            assert case["source"] is None, case["id"]


def test_the_held_out_set_is_real_and_disjoint() -> None:
    """A set you derived the numbers from is not a held-out set."""
    primary = {case["id"] for case in CASES}
    held_out = {case["id"] for case in HELD_OUT}
    assert primary and held_out
    assert not primary & held_out
    assert all(case["set"] == "held_out" for case in HELD_OUT)
    assert all(case["set"] == "primary" for case in CASES)


def test_the_benchmark_has_the_cases_the_task_named() -> None:
    """Polarity, distant numbers, entity scope, adjacent sentences, both scripts."""
    ids = {case["id"] for case in _all_cases()}
    for required in (
        "cjk-negation-dropped",
        "cjk-negation-exact",
        "entity-scope-narrow",
        "adjacent-sentence-second",
        "paraphrase-faithful",
        "squashed-boundary-lost",
    ):
        assert required in ids, required
    # distant number: a real sentence with a real number swapped for another on the same page
    assert "conll-wrong-number" in ids


def test_the_real_pdf_cases_are_read_from_the_demo_papers() -> None:
    real = [case for case in _all_cases() if case["provenance"]["kind"] == "real-pdf"]
    assert len(real) >= 4
    paths = {case["source"] for case in real}
    assert len(paths) == 2, "the two demo papers are the whole corpus this project owns"
    for case in real:
        assert Path(case["source"]).name in {p.name for p in DEMO_PAPERS}, case["id"]
        assert case["pages"] is None and case["provenance"]["licence"], case["id"]


def test_the_page_says_what_the_benchmark_cannot_do() -> None:
    assert DOC.is_file(), "docs/adversarial-benchmark.md has to exist"
    text = DOC.read_text(encoding="utf-8")
    flat = " ".join(text.split())
    assert "is this quote on that page" in flat
    assert "does the passage back the sentence" in flat
    # The data file spells the set `held_out`; the page may say it either way.
    lowered = flat.lower()
    assert "held-out" in lowered or "held out" in lowered or "held_out" in lowered
    assert "unknown" in flat.lower()
    assert "licensed" in flat.lower() or "licence" in flat.lower() or "license" in flat.lower()
    # No promise that a support label is computed.
    for forbidden in ("proves the claim", "proves your claim", "no judgment needed"):
        assert forbidden not in flat
    # One link, but a Markdown link names the path twice (label and target), so count lines.
    linked = [
        line
        for line in README.read_text(encoding="utf-8").splitlines()
        if "docs/adversarial-benchmark.md" in line
    ]
    assert len(linked) == 1, linked


def test_the_measured_version_is_recorded() -> None:
    measured = DATA["measured_with"]
    assert measured["citevouch"]
    assert measured["python"]
    assert measured["pypdf"]
    assert measured["date"] == "2026-11-15"


def test_no_case_is_silently_duplicated() -> None:
    ids = [case["id"] for case in _all_cases()]
    assert len(ids) == len(set(ids)), "two cases share an id, so one of them hides the other"


@pytest.mark.parametrize("case", [case for case in CASES], ids=lambda case: case["id"])
def test_each_primary_case_is_its_own_record(case: dict) -> None:
    """Parameterised so a drift names the case instead of the file."""
    assert _measure(case) == case["expected"]
